// Generates components/icons.tsx from Phosphor (MIT) bold SVGs.
import fs from "node:fs";

const icons = {
  phone: "phone",
  truck: "truck",
  car: "car-profile",
  jeep: "jeep",
  money: "money",
  recycle: "recycle",
  pin: "map-pin",
  clock: "clock",
  check: "check-circle",
  envelope: "envelope-simple",
  menu: "list",
  close: "x",
  caret: "caret-down",
  wrench: "wrench",
  arrow: "arrow-right",
  shield: "shield-check",
  lightning: "lightning",
  file: "file-text",
  gear: "gear-six",
  calendar: "calendar-blank",
  handshake: "handshake",
  leaf: "leaf",
};

const out = {};
for (const [name, file] of Object.entries(icons)) {
  const svg = fs.readFileSync(`node_modules/@phosphor-icons/core/assets/bold/${file}-bold.svg`, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const paths = [...inner.matchAll(/<path d="([^"]+)"\s*\/?>/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no paths for ${file}`);
  out[name] = paths.join(" ");
}

const src = `// Generated by scripts/build-icons.mjs from Phosphor Icons (MIT). Do not edit.
export const iconPaths = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof iconPaths;
`;
fs.writeFileSync("components/icon-paths.ts", src);
console.log("wrote", Object.keys(out).length, "icons");
