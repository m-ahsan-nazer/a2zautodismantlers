// Generates components/icons.tsx from Phosphor (MIT) SVGs.
import fs from "node:fs";

const icons = {
  headset: ["headset", "regular"],
  phone: ["phone", "regular"],
  pin: ["map-pin", "regular"],
  caretRight: ["caret-right", "bold"],
  caretDown: ["caret-down", "bold"],
  car: ["car-profile", "regular"],
  truck: ["truck", "fill"],
  van: ["van", "regular"],
  radio: ["radio-button", "bold"],
  medal: ["medal", "fill"],
  carFill: ["car", "fill"],
  star: ["star", "regular"],
  menu: ["list", "bold"],
  close: ["x", "bold"],
  play: ["play", "bold"],
  starFill: ["star", "fill"],
  quotes: ["quotes", "fill"],
  pause: ["pause", "fill"],
  playFill: ["play", "fill"],
  caretLeft: ["caret-left", "bold"],
  sealCheck: ["seal-check", "fill"],
};

const out = {};
for (const [name, [file, weight]] of Object.entries(icons)) {
  const suffix = weight === "regular" ? "" : `-${weight}`;
  const svg = fs.readFileSync(`node_modules/@phosphor-icons/core/assets/${weight}/${file}${suffix}.svg`, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const paths = [...inner.matchAll(/<path d="([^"]+)"\s*\/?>/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no paths for ${file}`);
  out[name] = paths.join(" ");
}

const src = `// Generated by scripts/build-icons.mjs from Phosphor Icons (MIT). Do not edit.
export const iconPaths = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof iconPaths;
`;
fs.writeFileSync("components/icon-paths.ts", src);
console.log("wrote", Object.keys(out).length, "icons");
